package com.anticheat.core.db

import com.anticheat.core.util.CoreLog
import java.security.MessageDigest

/**
 * 一次 schema 变更。
 *
 * <p>[checksum] 参与记录：迁移一旦执行过就不应再改。改了下一次启动会被检测出来并告警，
 * 而不是"静默地只在新库上生效"——那种前后不一致最终会表现为
 * "老服查询报列不存在，新服一切正常"，是最难查的一类问题。</p>
 */
class Migration(
    val version: Int,
    val name: String,
    val statements: List<String>
) {
    val checksum: String = sha1(name + "\n" + statements.joinToString("\n"))

    private fun sha1(text: String): String {
        val digest = MessageDigest.getInstance("SHA-1").digest(text.toByteArray(Charsets.UTF_8))
        val out = StringBuilder(digest.size * 2)
        for (byte in digest) {
            out.append(Character.forDigit((byte.toInt() shr 4) and 0xF, 16))
            out.append(Character.forDigit(byte.toInt() and 0xF, 16))
        }
        return out.toString()
    }
}

/**
 * 全部迁移，按版本号顺序执行。
 *
 * <h3>一套 DDL 同时给 H2 与 PostgreSQL</h3>
 * 见 [Sql] 的说明：时间用 `BIGINT`、IP/CIDR 用字符串、JSON 用字符串、
 * 自增用 `GENERATED BY DEFAULT AS IDENTITY`、"同时只允许一条生效"用可空唯一键。
 * 因此这里**没有任何方言分支**——如果将来某个语句只能在一个后端上跑，
 * 那说明写法退回了方言，应该改写法而不是加分支。
 *
 * <h3>为什么自建迁移器</h3>
 * 只需要三件事：有序、幂等、记录版本。为它引 Flyway/Liquibase 会多一份依赖，
 * 而本项目的 shade 规则里"谁提供同名类"已经出过两次线上事故。
 */
object Migrations {

    val ALL: List<Migration> by lazy { listOf(v001Basics(), v002RulesAndStats()) }

    @JvmStatic
    fun latestVersion(): Int = ALL.maxOfOrNull { it.version } ?: 0

    /**
     * V001：持久化主干——玩家档案 / 用户名历史 / IP 记录 / 封禁 / 违规 / 审计。
     */
    private fun v001Basics(): Migration = Migration(
        1, "basics", listOf(
            """
            CREATE TABLE IF NOT EXISTS player_profile (
                uuid             UUID PRIMARY KEY,
                name             VARCHAR(16) NOT NULL,
                first_seen       BIGINT      NOT NULL,
                last_seen        BIGINT      NOT NULL,
                last_ip          VARCHAR(64),
                sessions         INTEGER     NOT NULL DEFAULT 0,
                playtime_secs    BIGINT      NOT NULL DEFAULT 0,
                risk_score       REAL        NOT NULL DEFAULT 0,
                risk_updated     BIGINT,
                total_violations INTEGER     NOT NULL DEFAULT 0,
                violations_24h   INTEGER     NOT NULL DEFAULT 0,
                violations_7d    INTEGER     NOT NULL DEFAULT 0,
                profile_blob     VARCHAR,
                profile_updated  BIGINT
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_profile_name ON player_profile (name)",
            "CREATE INDEX IF NOT EXISTS idx_profile_last_seen ON player_profile (last_seen)",
            "CREATE INDEX IF NOT EXISTS idx_profile_risk ON player_profile (risk_score)",
            // 用户名历史单独一张表：可以按旧名反查账号（"这个号以前叫什么"、
            // "这个名字被哪些 uuid 用过"），这是原来那种"把历史塞进一个字符串"做不到的。
            """
            CREATE TABLE IF NOT EXISTS player_name (
                uuid       UUID        NOT NULL,
                name       VARCHAR(16) NOT NULL,
                first_seen BIGINT      NOT NULL,
                last_seen  BIGINT      NOT NULL,
                uses       INTEGER     NOT NULL DEFAULT 1,
                PRIMARY KEY (uuid, name)
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_player_name_name ON player_name (name)",
            // IP 与网段都存字符串：网段匹配在 IpIntel 里做（纯逻辑、已单测），
            // 这样 H2 与 PostgreSQL 跑的是同一套 SQL，不需要 INET/CIDR 类型与 >>= 操作符。
            """
            CREATE TABLE IF NOT EXISTS player_ip (
                uuid        UUID        NOT NULL,
                ip          VARCHAR(64) NOT NULL,
                ip_family   SMALLINT    NOT NULL,
                cidr        VARCHAR(64) NOT NULL,
                asn         INTEGER,
                asn_org     VARCHAR(128),
                country     VARCHAR(8),
                first_seen  BIGINT      NOT NULL,
                last_seen   BIGINT      NOT NULL,
                login_count INTEGER     NOT NULL DEFAULT 1,
                PRIMARY KEY (uuid, ip)
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_player_ip_ip ON player_ip (ip)",
            "CREATE INDEX IF NOT EXISTS idx_player_ip_cidr ON player_ip (cidr)",
            "CREATE INDEX IF NOT EXISTS idx_player_ip_last_seen ON player_ip (last_seen)",
            // 封禁：kind=uuid/ip/cidr，scope=temp/perm，status=active/expired/revoked。
            // active_key 只在生效时非空（'uuid:<id>' / 'ip:<x>' / 'cidr:<x>'），
            // 靠它的唯一约束保证"同一目标同时只有一条生效封禁"——两个引擎对
            // "唯一索引里可以有多少个 NULL" 的语义一致（可以任意多个），
            // 而 PostgreSQL 的部分唯一索引 H2 没有。
            """
            CREATE TABLE IF NOT EXISTS ban (
                id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kind          VARCHAR(8)   NOT NULL,
                target        VARCHAR(64)  NOT NULL,
                name          VARCHAR(16),
                uuid          UUID,
                scope         VARCHAR(8)   NOT NULL,
                reason        VARCHAR(255) NOT NULL,
                operator      VARCHAR(32)  NOT NULL,
                issued_at     BIGINT       NOT NULL,
                expires_at    BIGINT,
                status        VARCHAR(8)   NOT NULL,
                revoked_by    VARCHAR(32),
                revoked_at    BIGINT,
                revoke_reason VARCHAR(255),
                server_name   VARCHAR(32),
                violation_id  BIGINT,
                active_key    VARCHAR(96),
                CONSTRAINT uq_ban_active UNIQUE (active_key)
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_ban_uuid ON ban (uuid)",
            "CREATE INDEX IF NOT EXISTS idx_ban_target ON ban (target)",
            "CREATE INDEX IF NOT EXISTS idx_ban_status_expires ON ban (status, expires_at)",
            "CREATE INDEX IF NOT EXISTS idx_ban_issued ON ban (issued_at)",
            """
            CREATE TABLE IF NOT EXISTS violation (
                id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                uuid           UUID        NOT NULL,
                name           VARCHAR(16) NOT NULL,
                check_name     VARCHAR(32) NOT NULL,
                check_group    VARCHAR(24),
                vl             REAL        NOT NULL,
                vl_delta       REAL        NOT NULL,
                severity       SMALLINT    NOT NULL DEFAULT 1,
                created_at     BIGINT      NOT NULL,
                day_bucket     BIGINT      NOT NULL,
                server_name    VARCHAR(32),
                world          VARCHAR(64),
                x              DOUBLE PRECISION,
                y              DOUBLE PRECISION,
                z              DOUBLE PRECISION,
                ping           INTEGER,
                tps            REAL,
                client_version VARCHAR(24),
                packet_type    VARCHAR(48),
                detail         VARCHAR,
                experimental   BOOLEAN     NOT NULL DEFAULT FALSE,
                punished       BOOLEAN     NOT NULL DEFAULT FALSE,
                punish_action  VARCHAR(24)
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_viol_time ON violation (created_at)",
            "CREATE INDEX IF NOT EXISTS idx_viol_uuid_time ON violation (uuid, created_at)",
            "CREATE INDEX IF NOT EXISTS idx_viol_check_time ON violation (check_name, created_at)",
