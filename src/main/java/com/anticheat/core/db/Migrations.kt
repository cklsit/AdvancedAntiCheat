    /**
     * V002：规则与统计——检测阈值 / 惩罚阶梯 / 白名单 / 检查命中率 / 风险画像。
     */
    private fun v002RulesAndStats(): Migration = Migration(
        2, "rules_and_stats", listOf(
            """
            CREATE TABLE IF NOT EXISTS check_rule (
                check_name   VARCHAR(32) PRIMARY KEY,
                enabled      BOOLEAN     NOT NULL DEFAULT TRUE,
                decay        REAL,
                setback      REAL,
                experimental BOOLEAN     NOT NULL DEFAULT FALSE,
                description  VARCHAR(255),
                thresholds   VARCHAR,
                updated_at   BIGINT      NOT NULL,
                updated_by   VARCHAR(32)
            )
            """.trimIndent(),
            """
            CREATE TABLE IF NOT EXISTS punishment_ladder (
                step       SMALLINT    PRIMARY KEY,
                min_vl     REAL        NOT NULL,
                action     VARCHAR(24) NOT NULL,
                duration   VARCHAR(24),
                reason     VARCHAR(255),
                updated_at BIGINT      NOT NULL
            )
            """.trimIndent(),
            """
            CREATE TABLE IF NOT EXISTS whitelist_entry (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                uuid       UUID,
                name       VARCHAR(16),
                reason     VARCHAR(255),
                added_by   VARCHAR(32),
                added_at   BIGINT NOT NULL,
                expires_at BIGINT,
                active_key VARCHAR(48),
                CONSTRAINT uq_whitelist_active UNIQUE (active_key)
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_whitelist_name ON whitelist_entry (name)",
            """
            CREATE TABLE IF NOT EXISTS check_stat (
                bucket      BIGINT      NOT NULL,
                check_name  VARCHAR(32) NOT NULL,
                evaluations BIGINT      NOT NULL DEFAULT 0,
                flags       BIGINT      NOT NULL DEFAULT 0,
                vl_sum      REAL        NOT NULL DEFAULT 0,
                players     INTEGER     NOT NULL DEFAULT 0,
                PRIMARY KEY (bucket, check_name)
            )
            """.trimIndent(),
            """
            CREATE TABLE IF NOT EXISTS risk_snapshot (
                id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                uuid         UUID     NOT NULL,
                score        REAL     NOT NULL,
                violations   INTEGER  NOT NULL,
                window_hours SMALLINT NOT NULL,
                computed_at  BIGINT   NOT NULL
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_risk_snapshot_uuid ON risk_snapshot (uuid, computed_at)",
            // ---- 视图：聚合口径只在视图里定义一次，看板/命令/排障共用 ----
            // 先 DROP 再 CREATE：`CREATE OR REPLACE VIEW` 的列兼容要求两个引擎不一致
            "DROP VIEW IF EXISTS v_violation_trend",
            "CREATE VIEW v_violation_trend AS " +
                // 别名刻意叫 day_bucket 而不是 day：DAY 是 SQL 保留字，
                // H2 会直接拒绝（PG 能过但属于靠运气），而两个后端必须跑同一套 DDL
                "SELECT day_bucket, check_name, count(*) AS violations, " +
                "count(DISTINCT uuid) AS players, avg(vl_delta) AS avg_vl_delta, max(vl) AS max_vl " +
                "FROM violation GROUP BY day_bucket, check_name",
            "DROP VIEW IF EXISTS v_check_hit_rate",
            "CREATE VIEW v_check_hit_rate AS " +
                "SELECT check_name, sum(evaluations) AS evaluations, sum(flags) AS flags, " +
                "CASE WHEN sum(evaluations) > 0 THEN sum(flags) * 1.0 / sum(evaluations) ELSE NULL END AS hit_rate, " +
                "max(bucket) AS last_bucket FROM check_stat GROUP BY check_name",
            "DROP VIEW IF EXISTS v_player_risk",
            // 风险画像只读档案表里**已算好**的列：近 24h/7d 违规数由
            // RiskRefresh 任务写入（每 risk-refresh-minutes 一次）。
            // 这样做的原因：视图里算"最近 24 小时"需要 now()/interval 这类方言函数，
            // 而把它们换成"写入时算好"既省了每次查询的全表扫描，也让两个引擎完全一致。
            "CREATE VIEW v_player_risk AS " +
                "SELECT uuid, name, risk_score, total_violations, violations_24h, violations_7d, last_seen, last_ip " +
                "FROM player_profile"
        )
    )
}

/** 迁移执行结果（用于启动日志与测试断言）。 */
class MigrationResult(
    val applied: List<Int>,
    val skipped: Int,
    val checksumMismatches: List<Int>,
    val latestVersion: Int
) {
    fun describe(): String {
        val base = "schema v" + latestVersion +
            "（本次执行 " + applied.size + " 个迁移，跳过 " + skipped + " 个已执行版本）"
        if (checksumMismatches.isEmpty()) return base
        return base + " ⚠ 校验和不一致（迁移被改过）: " + checksumMismatches
    }
}

/**
 * 迁移执行器。
 *
 * <p>每个迁移在**独立事务**里执行：中途失败时该版本整体回滚，
 * 不会留下"建了一半的表"——那种状态下重跑 `CREATE TABLE IF NOT EXISTS` 恰好能建完，
 * 但索引与视图会缺，而且要人工判断缺了什么。</p>
 */
class Migrator(private val pool: JdbcPool) {

    fun migrate(): MigrationResult {
        ensureVersionTable()

        val applied = ArrayList<Int>()
        val mismatches = ArrayList<Int>()
        var skipped = 0

        val known = readApplied()
        for (migration in Migrations.ALL) {
            val recorded = known[migration.version]
            if (recorded != null) {
                if (recorded != migration.checksum) {
                    mismatches.add(migration.version)
                    CoreLog.warn(
                        "数据库迁移 v" + migration.version + " 的校验和与记录不一致：" +
                            "该版本已被修改但不会重跑（库结构可能与代码不再一致，建议手工核对）"
                    )
                }
                skipped++
                continue
            }
            pool.withTransaction { connection ->
                connection.createStatement().use { statement ->
                    for (sql in migration.statements) {
                        statement.execute(sql)
                    }
                }
                true
            }
            pool.withTransaction { connection ->
                connection.prepareStatement(
                    "INSERT INTO schema_version (version, name, checksum, applied_at) VALUES (?, ?, ?, ?)"
                ).use { insert ->
                    insert.setInt(1, migration.version)
                    insert.setString(2, migration.name)
                    insert.setString(3, migration.checksum)
                    insert.setLong(4, System.currentTimeMillis())
                    insert.executeUpdate()
                }
                true
            }
            applied.add(migration.version)
        }

        return MigrationResult(applied, skipped, mismatches, Migrations.latestVersion())
    }

    private fun ensureVersionTable() {
        pool.withConnection { connection ->
            connection.createStatement().use { statement ->
                statement.execute(
                    """
                    CREATE TABLE IF NOT EXISTS schema_version (
                        version    INTEGER     PRIMARY KEY,
                        name       VARCHAR(64) NOT NULL,
                        checksum   VARCHAR(64) NOT NULL,
                        applied_at BIGINT      NOT NULL
                    )
                    """.trimIndent()
                )
            }
            true
        }
    }

    private fun readApplied(): Map<Int, String> {
        val result = HashMap<Int, String>()
        pool.withConnection { connection ->
            connection.createStatement().use { statement ->
                statement.executeQuery("SELECT version, checksum FROM schema_version").use { rows ->
                    while (rows.next()) {
                        result[rows.getInt("version")] = rows.getString("checksum")
                    }
                }
            }
            true
        }
        return result
    }
}
