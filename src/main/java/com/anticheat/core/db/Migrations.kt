            // TIMESTAMP 在 H2 里是数据类型关键字，当列名有兼容风险。
            """
            CREATE TABLE IF NOT EXISTS audit_log (
                id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ts            BIGINT NOT NULL,
                operator      VARCHAR(64),
